//! Edge function source bakers (port of `lib/supabase-paykit/function-templates.ts` + `codegen.ts#hashPaykitDrafts`).

use super::sql;
use super::{DraftState, FeatureDraft, PlanDraft};
use serde_json::{json, Value};

const SHARED_TS: &str = include_str!("assets/shared_ts.js");
const WEBHOOK_BODY_TS: &str = include_str!("assets/webhook_body_ts.js");
const API_BODY_TS: &str = include_str!("assets/api_body_ts.js");

#[derive(Clone, Debug)]
pub struct BuiltSource {
    pub slug: String,
    pub source: String,
    pub draft_hash: String,
}

/// Deterministic non-crypto hash for drift detection (djb2, 8 hex digits).
pub fn hash_paykit_drafts(state: &DraftState) -> String {
    let input = serde_json::to_string(&json!({
        "features": &state.features,
        "plans": &state.plans,
    }))
    .unwrap_or_else(|_| "{}".into());
    let mut hash: i32 = 5381;
    for b in input.bytes() {
        hash = hash.wrapping_shl(5).wrapping_add(hash).wrapping_add(b as i32);
    }
    format!("{:08x}", hash as u32)
}

fn feature_obj(f: &FeatureDraft) -> Value {
    json!({
        "id": f.id,
        "type": if f.feature_type.is_empty() { "boolean" } else { &f.feature_type },
        "description": f.description,
    })
}

fn plan_obj(p: &PlanDraft) -> Value {
    json!({
        "id": p.id,
        "name": p.name,
        "group": if p.group.is_empty() { "base" } else { &p.group },
        "default": p.default,
        "priceAmount": p.price_amount,
        "priceInterval": p.price_interval,
        "priceCurrency": p.price_currency,
        "includes": p.includes.iter().map(|inc| json!({
            "featureId": inc.feature_id,
            "limit": inc.limit,
            "reset": inc.reset,
        })).collect::<Vec<_>>(),
    })
}

pub fn template_data(drafts: &DraftState) -> Value {
    let hash = hash_paykit_drafts(drafts);
    json!({
        "hash": hash,
        "schemaVersion": sql::schema_version(),
        "features": drafts.features.iter().map(feature_obj).collect::<Vec<_>>(),
        "plans": drafts.plans.iter().map(plan_obj).collect::<Vec<_>>(),
    })
}

fn build_source(kind: &str, data: &Value) -> BuiltSource {
    let hash = data.get("hash").and_then(Value::as_str).unwrap_or("");
    let schema = data.get("schemaVersion").and_then(Value::as_str).unwrap_or(sql::schema_version());
    let data_json = serde_json::to_string(data).unwrap_or_else(|_| "{}".into());
    let header = format!(
        "// Auto-generated by RexaDB — PayKit billing for Supabase.\n\
         // Draft hash: {hash} | schema: {schema}\n\
         // Deployed via Supabase Management API (functions/deploy).\n\
         // Docs: https://paykit.sh/docs — billing tables: paykit.* (do not hand-edit).\n"
    );
    let body = if kind == "webhook" { WEBHOOK_BODY_TS } else { API_BODY_TS };
    let source = format!(
        "{header}\nvar PAYKIT_DATA = {data_json};\nvar PAYKIT_HASH = '{hash}';\nvar PAYKIT_SCHEMA = '{schema}';\nvar PAYKIT_TEMPLATE_VERSION = '{}';\n\n{SHARED_TS}\n\n{body}\n",
        sql::template_version(),
    );
    let slug = if kind == "webhook" { sql::webhook_slug() } else { sql::api_slug() };
    BuiltSource { slug: slug.into(), source, draft_hash: hash.into() }
}

pub fn build_webhook_source(drafts: &DraftState) -> BuiltSource {
    build_source("webhook", &template_data(drafts))
}

pub fn build_api_source(drafts: &DraftState) -> BuiltSource {
    build_source("api", &template_data(drafts))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::payments::PlanDraft;

    #[test]
    fn hash_smoke() {
        let d = DraftState {
            version: 1,
            features: vec![],
            plans: vec![PlanDraft { id: "free".into(), name: "Free".into(), group: "base".into(), default: Some(true), ..Default::default() }],
            updated_at: 1,
        };
        let h = hash_paykit_drafts(&d);
        assert_eq!(h.len(), 8);
        assert!(h.chars().all(|c| c.is_ascii_hexdigit()));
        assert_eq!(hash_paykit_drafts(&d), h);
        let src = build_api_source(&d);
        assert!(src.source.contains("var PAYKIT_DATA = "));
        assert!(src.source.contains(&format!("PAYKIT_TEMPLATE_VERSION = '{}'", sql::template_version())));
        assert_eq!(src.slug, "paykit-api");
        assert_eq!(build_webhook_source(&d).slug, "paykit-webhook");
    }
}
