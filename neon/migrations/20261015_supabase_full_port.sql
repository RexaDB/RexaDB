-- Full-fidelity port of the live Supabase public schema for autumn-firefly.

-- Sources: introspection via RexaDB MCP (tables, uniques, RLS, triggers,

--   function defs). Idempotent: safe to re-run.

-- Deliberate deviations from Supabase (documented):

--   1. auth.uid() rewritten to public.auth_uid() (JWT-claim fallback shim).

--   2. FK constraints omitted (auth-linked FKs invalid on Neon; none in public).

--   3. Serial sequences replaced by GENERATED ... AS IDENTITY.

--   4. +profiles_self_insert policy (client-side profile upsert needs it).

--   5. save_user_settings_sync: upstream validations + atomic ON CONFLICT..WHERE

--      guard (fixes lost-update race; returns winning row with applied=false).

--   6. redeem_gift_code + workspace RPCs skipped: reference dropped tables

--      (gift_codes, gift_code_redemptions, workspaces*) upstream too.

--   7. handle_new_user / enforce_max_* (auth.* triggers) skipped: no auth

--      schema on Neon; profile creation happens in syncAuthenticatedUserProfile.



