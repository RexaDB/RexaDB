-- save_user_settings_sync: upstream validations + atomic staleness guard.
CREATE OR REPLACE FUNCTION public.save_user_settings_sync(p_payload jsonb, p_client_updated_at timestamptz)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $fn$
DECLARE
  v_uid uuid := public.auth_uid();
  v_row public.user_settings_sync%ROWTYPE;
  v_applied boolean := false;
  v_count integer := 0;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'Missing user id'; END IF;
  IF p_payload IS NULL OR jsonb_typeof(p_payload) <> 'object' THEN RAISE EXCEPTION 'Invalid settings payload'; END IF;
  IF p_client_updated_at IS NULL THEN RAISE EXCEPTION 'Missing client_updated_at'; END IF;
  INSERT INTO public.user_settings_sync AS s (user_id, payload, client_updated_at, updated_at)
  VALUES (v_uid, p_payload, p_client_updated_at, now())
  ON CONFLICT (user_id) DO UPDATE SET payload = EXCLUDED.payload,
    client_updated_at = EXCLUDED.client_updated_at, updated_at = now()
  WHERE EXCLUDED.client_updated_at >= s.client_updated_at
  RETURNING * INTO v_row;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  IF v_count = 0 THEN
    SELECT * INTO v_row FROM public.user_settings_sync WHERE user_id = v_uid;
  ELSE
    v_applied := true;
  END IF;
  RETURN jsonb_build_object('applied', v_applied, 'user_id', v_row.user_id, 'payload', v_row.payload,
    'client_updated_at', v_row.client_updated_at, 'updated_at', v_row.updated_at);
END;
$fn$;



