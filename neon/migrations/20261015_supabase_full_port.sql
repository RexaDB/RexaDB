DROP FUNCTION IF EXISTS public.delete_cloud_connection(uuid);
CREATE OR REPLACE FUNCTION public.delete_cloud_connection(p_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_user_id uuid := public.auth_uid();
begin
  if v_user_id is null then
    return jsonb_build_object('success', false, 'error', 'Unauthorized.');
  end if;

  delete from public.cloud_connections
  where id = p_id
    and user_id = v_user_id;

  return jsonb_build_object('success', true);
end;
$function$;
CREATE OR REPLACE FUNCTION public.extend_otl_updates(p_user_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_existing timestamptz;
BEGIN
  SELECT updates_until INTO v_existing
  FROM public.user_subscriptions
  WHERE user_id = p_user_id
  ORDER BY created_at DESC
  LIMIT 1;

  INSERT INTO public.user_subscriptions
    (user_id, plan, status, updates_until)
  VALUES (
    p_user_id,
    'otl'::public.subscription_plan,
    'active'::public.subscription_status,
    GREATEST(COALESCE(v_existing, now()), now()) + interval '12 months'
  )
  ON CONFLICT (user_id) DO UPDATE
  SET plan = 'otl'::public.subscription_plan,
      status = 'active'::public.subscription_status,
      updates_until = GREATEST(
        COALESCE(user_subscriptions.updates_until, now()),
        now()
      ) + interval '12 months',
      ends_at = NULL,
      updated_at = now();
END;
$function$;
CREATE OR REPLACE FUNCTION public.get_my_display_name()
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_user_id uuid := public.auth_uid();
  v_name text;
begin
  if v_user_id is null then
    return null;
  end if;

  select nullif(trim(full_name), '')
  into v_name
  from public.profiles
  where id = v_user_id;

  return v_name;
end;
$function$;
