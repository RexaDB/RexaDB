CREATE OR REPLACE FUNCTION public.log_app_error(p_error_type text DEFAULT 'unknown'::text, p_message text DEFAULT NULL::text, p_stack text DEFAULT NULL::text, p_url text DEFAULT NULL::text, p_component_stack text DEFAULT NULL::text, p_metadata jsonb DEFAULT '{}'::jsonb, p_app_version text DEFAULT NULL::text, p_os text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_user_id uuid;
  v_total_size bigint;
  v_id uuid;
  v_max_bytes constant bigint := 51200;
begin
  v_total_size :=
    coalesce(octet_length(p_error_type), 0) +
    coalesce(octet_length(p_message), 0) +
    coalesce(octet_length(p_stack), 0) +
    coalesce(octet_length(p_url), 0) +
    coalesce(octet_length(p_component_stack), 0) +
    coalesce(octet_length(p_metadata::text), 0) +
    coalesce(octet_length(p_app_version), 0) +
    coalesce(octet_length(p_os), 0);

  if v_total_size > v_max_bytes then
    raise exception 'Error payload too large: % bytes (max %)', v_total_size, v_max_bytes;
  end if;

  begin
    v_user_id := public.auth_uid();
  exception
    when others then
      v_user_id := null;
  end;

  insert into public.app_errors (
    user_id, error_type, message, stack, url,
    component_stack, metadata, app_version, os
  ) values (
    v_user_id, p_error_type, p_message, p_stack, p_url,
    p_component_stack, p_metadata, p_app_version, p_os
  ) returning id into v_id;

  return v_id;
end;
$function$;
CREATE OR REPLACE FUNCTION public.publish_community_theme(p_name text, p_description text, p_theme_type text, p_theme_json jsonb)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_user_id uuid := public.auth_uid();
  v_author_name text;
