function normalize(value: unknown): unknown {
  if (value === null || value === undefined) return null;
  if (typeof value === "object") return JSON.stringify(value);
  return value;
}

export default async function handler(req: Request): Promise<Response> {
  if (!TOKEN || req.headers.get("authorization") !== `Bearer ${TOKEN}`) {
    return new Response("unauthorized", { status: 401 });
  }
  let body: any;
  try {
    body = await req.json();
  } catch {
    return new Response("bad json", { status: 400 });
  }
  try {
    if (body.action === "ddl") {
      await pool.query(SCHEMA_SQL);
      return Response.json({ ok: true });
    }
    if (body.action === "load") {
      const cols = TABLES[String(body.table)];
      if (!cols || !Array.isArray(body.rows)) {
        return new Response("unknown table or rows", { status: 400 });
      }
      const quoted = cols.map((c) => `"${c}"`).join(",");
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        let n = 0;
        for (const row of body.rows) {
          const vals = cols.map((c) => normalize((row as any)?.[c]));
          await client.query(
            `INSERT INTO public."${body.table}" (${quoted}) VALUES (${cols.map((_, i) => `$${i + 1}`).join(",")} ) ON CONFLICT DO NOTHING`,
            vals,
          );
          n++;
        }
        await client.query("COMMIT");
        return Response.json({ ok: true, inserted: n });
      } catch (e) {
        await client.query("ROLLBACK");
        return Response.json({ ok: false, error: String(e) }, { status: 500 });
      } finally {
        client.release();
      }
    }
    if (body.action === "count") {
      const cols = TABLES[String(body.table)];
      if (!cols) {
        return new Response("unknown table", { status: 400 });
      }
      const r = await pool.query(`SELECT count(*)::int AS n FROM public."${body.table}"`);
      return Response.json({ ok: true, table: body.table, count: r.rows[0].n });
    }
    if (body.action === "exec" && typeof body.sql === "string") {
      const r = await pool.query(body.sql);
      return Response.json({ ok: true, rows: r.rows ?? null });
    }
    return new Response("bad action", { status: 400 });
  } catch (e) {
    return Response.json({ ok: false, error: String(e) }, { status: 500 });
  }
}
